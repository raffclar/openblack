"""Sort the verified candidates into confirmed, review and test-only, and write the report.

Usage: python tools/dead_code/dc_report.py <repo root> <verified.md> <report.md>

confirmed: no index use, and no other code mention of the name (declarations only), and the name has one definition.
review: no index use, but a code mention exists, or the name has more than one definition.
test-only: the only uses are in test/.
ctor-unused: a constructor with no direct call; a call through make_unique or emplace can hide one, so check by text.
"""

import collections
import re
import subprocess
import sys

TEXT = (".cpp", ".h", ".hpp", ".inl", ".cmake", ".txt", ".py", ".lua", ".in", ".json")


def is_comment(text):
    return text.strip().startswith(("//", "///", "*", "/*"))


def main():
    root, verified, report = sys.argv[1:4]
    names = subprocess.run(["git", "-C", root, "ls-files"], capture_output=True, text=True).stdout.splitlines()
    lines = collections.defaultdict(list)  # name -> [(file, line, text)]
    word = re.compile(r"[A-Za-z_]\w*")
    for f in names:
        if not f.endswith(TEXT) or f.startswith(("vcpkg", "externals", "assets")):
            continue
        try:
            with open(root + "/" + f, encoding="utf-8", errors="ignore") as fh:
                body = fh.read().split("\n")
        except OSError:
            continue
        for i, text in enumerate(body, 1):
            for m in set(word.findall(text)):
                lines[m].append((f, i, text))
    rows = []
    with open(verified, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith(("| class", "|---")):
                continue
            p = [x.strip() for x in line.strip().strip("|").split("|")]
            if len(p) >= 6:
                rows.append(p)
    defcount = collections.Counter(r[1].split("::")[-1] for r in rows)
    out = {"confirmed": [], "review": [], "ctor-unused": [], "test-only": []}
    for cls, sym, loc, kind, ev, _ in rows:
        name = sym.split("::")[-1]
        f, ln = loc.rsplit(":", 1)
        others = [x for x in lines[name] if not (x[0] == f and x[1] == int(ln))]
        code = [x for x in others if not is_comment(x[2])]
        decl = re.compile(r"^\s*(\[\[\w+\]\]\s*)*(static\s+|virtual\s+|inline\s+|constexpr\s+)*[\w:<>,&\*\s]+?[\s&\*]%s"
                          r"\s*\(.*\)\s*(const)?\s*(noexcept)?\s*(override)?\s*;\s*(//.*)?$" % re.escape(name))
        nondecl = [x for x in code if not (decl.match(x[2]) and "return" not in x[2].split(name)[0])]
        if cls == "dead":
            if not nondecl and defcount[name] == 1:
                out["confirmed"].append((sym, loc, kind, "no other mention (declarations only: %d)" % len(code)))
            else:
                first = (nondecl[0][0] + ":" + str(nondecl[0][1])) if nondecl else "ambiguous name"
                out["review"].append((sym, loc, kind, "%d other code mentions e.g. %s" % (len(nondecl), first)))
        elif cls == "ctor-unused":
            out["ctor-unused"].append((sym, loc, kind, "%d other code mentions of the name" % len(nondecl)))
        elif cls == "test-only":
            out["test-only"].append((sym, loc, kind, ev))
    with open(report, "w", encoding="utf-8") as o:
        o.write("# Dead code report\n\nGenerated by tools/dead_code. Counts: " +
                ", ".join("%s %d" % (k, len(v)) for k, v in out.items()) + "\n")
        for title, rs in out.items():
            o.write("\n## %s (%d)\n\n| symbol | file:line | kind | evidence |\n|---|---|---|---|\n" % (title, len(rs)))
            for r in sorted(rs, key=lambda x: x[1]):
                o.write("| %s | %s | %s | %s |\n" % r)
    print({k: len(v) for k, v in out.items()})


if __name__ == "__main__":
    main()
